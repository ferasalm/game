#!/usr/bin/env python3
"""Writes docs/MAP.md from each file's purpose line, so the map never drifts. --check: exit 1 if stale.

Purpose line: the first "## " line of a .gd, the docstring or first comment of a .py/.sh/.yml; a content
.json shows its kind and item count. Run after adding, moving or deleting files (tools/check.sh runs --check).
"""
import json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP = ROOT / "docs/MAP.md"
SKIP = re.compile(r"^(docs/|assets/|\.claude/|README|CLAUDE|HANDOFF|\.git)|(\.import|\.uid|\.gdignore)$")
HEADER = """# Map (generated by tools/map.py; do not edit by hand)

Where things live. Read before a code change; grep this file instead of listing folders.
Architecture and rules: docs/ARCHITECTURE.md. Folder rule: a feature keeps its logic, defs, view and tests together.
"""


def purpose(path: pathlib.Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    if path.suffix == ".gd":
        block = []
        for line in lines[:12]:
            if line.startswith("## "):
                block.append(line[3:].strip())
            elif block:
                break
        joined = " ".join(block)
        return joined.split(". ")[0].rstrip(".") if joined else ""
    if path.suffix == ".py":
        m = re.search(r'"""(.+?)(\n|""")', text)
        return m.group(1).strip() if m else ""
    if path.suffix in (".sh", ".yml", ".yaml"):
        return next((l.lstrip("# ").strip() for l in lines[:4] if l.startswith("# ") and not l.startswith("#!")), "")
    if path.suffix == ".json":
        try:
            data = json.loads(text)
            return f"content: {data.get('kind', '?')} x{len(data.get('items', []))}"
        except (ValueError, AttributeError):
            return "json"
    if path.suffix == ".tscn":
        return "scene"
    return ""


def build() -> tuple[str, list[str]]:
    listed = subprocess.run(["git", "ls-files", "--cached"],
                            cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    # set(): a file in a merge conflict is listed once per stage
    files = [f for f in set(listed) if not SKIP.search(f) and (ROOT / f).is_file()]
    files.sort(key=lambda f: (f.split("/")[0] if "/" in f else "", f))
    out, missing, section = [HEADER], [], None
    for f in files:
        top = f.split("/")[0] if "/" in f else "(root)"
        if top != section:
            section = top
            out.append(f"\n## {top}")
        p = purpose(ROOT / f)
        if not p and pathlib.Path(f).suffix in (".gd", ".py", ".sh", ".yml"):
            missing.append(f)
        out.append(f"- `{f}`" + (f": {p}" if p else ""))
    return "\n".join(out) + "\n", missing


def main() -> int:
    text, missing = build()
    for f in missing:
        print(f"map: {f} has no purpose line")
    if "--check" in sys.argv:
        stale = not MAP.exists() or MAP.read_text(encoding="utf-8") != text
        if stale:
            print("map: docs/MAP.md is stale; run python3 tools/map.py")
        return 1 if stale or missing else 0
    MAP.write_text(text, encoding="utf-8", newline="\n")
    print(f"map: wrote docs/MAP.md ({text.count(chr(10) + '- ')} files)")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
