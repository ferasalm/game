#!/usr/bin/env python3
"""Maps every doc node, its references, orphans and duplicated lines into docs/DOCMAP.md. --check: exit 1 on a stale map or a new dangling reference.

A node is an .md under the root except docs/archive, docs/research, inbox, assets, .godot, .check, worktrees and the
map itself. An edge is a repo-path token or an @file.md import that exists from the root or the node's own folder.
Dangling pairs live in docs/doc_graph_allow.txt as "node :: token"; --baseline writes today's pairs there so only new
ones fail. --who-mentions TERM greps the nodes and the code under tools, plugins, .claude, features and core.
"""
import argparse
import os
import pathlib
import re
import sys

SELF = "docs/DOCMAP.md"
ALLOW = "docs/doc_graph_allow.txt"
SKIP = re.compile(r"^(docs/(archive|research)|inbox|assets|\.godot|\.check|\.claude/worktrees|\.git)(/|$)")
EXTS = ("md", "py", "sh", "gd", "json", "csv", "tscn", "tres", "cfg", "conf", "yml")
CODE_DIRS = ("tools", "plugins", ".claude", "features", "core")
CODE_EXTS = (".py", ".sh", ".gd", ".json", ".conf", ".csv")
ROOTS = ("CLAUDE.md", "HANDOFF.md", "README.md", "docs/MAP.md")
BAD = ("*", "<", ">", "{", "$", " ", "..", "http", "//")
TOKEN = re.compile(r"[A-Za-z0-9_./-]+")
IMPORT = re.compile(r"@([A-Za-z0-9_./-]+\.md)")
HEADER = """# Doc map (generated by tools/doc_graph.py; do not edit by hand)

Every .md node with its purpose and its inbound and outbound doc edges, then the dangling references, the orphans
and the 80+ character lines that live in two docs. Rebuild after moving, renaming or adding a doc:
python tools/doc_graph.py. A stale map or a new dangling reference fails tools/check.sh; orphans and overlaps warn.
"""


def walk(root: pathlib.Path) -> list:
    """Every .md under the root, minus the skipped folders and the map itself, sorted by path."""
    out = []
    for dirpath, dirs, files in os.walk(root):
        rel = pathlib.Path(dirpath).relative_to(root).as_posix()
        rel = "" if rel == "." else rel + "/"
        dirs[:] = sorted(d for d in dirs if not SKIP.match(rel + d))
        out += [rel + f for f in files if f.endswith(".md") and rel + f != SELF]
    return sorted(out)


def purpose(text: str) -> str:
    """The front-matter description, else the first line that is not blank and not only heading marks."""
    lines = text.splitlines()
    start = 1 if lines and lines[0].strip() == "---" else 0
    if start:
        start = next((i + 1 for i in range(1, len(lines)) if lines[i].strip() == "---"), 0)
        found = next((re.match(r"\s*description:\s*(.+)", l) for l in lines[1:start]), None)
        if found:
            return found.group(1).strip().strip("\"'")
    first = next((l.strip() for l in lines[start:] if l.strip() and not re.fullmatch(r"#+", l.strip())), "")
    return first.lstrip("#").strip()


def refs(text: str) -> list:
    """Every repo-path token and @file.md import in a node, in file order, without duplicates."""
    found = [t for t in (m.group(0) for m in TOKEN.finditer(text))
             if "/" in t and not t.startswith("/") and not any(bad in t for bad in BAD)
             and (t.endswith("/") or t.rsplit(".", 1)[-1] in EXTS)]
    found += [m.group(1) for m in IMPORT.finditer(text)
              if not m.group(1).startswith("/") and not any(bad in m.group(1) for bad in BAD)]
    return list(dict.fromkeys(found))


def resolve(root: pathlib.Path, node: str, tok: str) -> str:
    """The token as a repo path when it exists from the root or the node's folder, else ''; build artifacts never count."""
    here = pathlib.PurePosixPath(node).parent
    for cand in (tok, (here / tok).as_posix()):
        cand = cand.rstrip("/")
        if cand.split("/")[0] not in (".check", ".godot", ".git") and (root / cand).exists():
            return cand
    return ""


def allowlist(root: pathlib.Path) -> set:
    """The node :: token pairs the allowlist file silences (# comments and blank lines skipped)."""
    if not (root / ALLOW).exists():
        return set()
    rows = (line.split("#", 1)[0].strip() for line in (root / ALLOW).read_text(encoding="utf-8").splitlines())
    return {tuple(x.strip() for x in row.split("::", 1)) for row in rows if "::" in row}


def overlaps(texts: dict) -> list:
    """Normalized 80+ character lines that appear in two or more nodes, outside code fences and anchor lists."""
    seen = {}
    for name, text in texts.items():
        fenced = False
        for line in text.splitlines():
            fenced = not fenced if line.strip().startswith("```") else fenced
            norm = " ".join(line.lower().split())
            if not fenced and len(norm) >= 80 and not re.match(r"[-*] \[.+\]\(#", norm):
                seen.setdefault(norm, set()).add(name)
    return sorted((norm, sorted(names)) for norm, names in seen.items() if len(names) > 1)


def graph(root: pathlib.Path) -> dict:
    """Nodes, purposes, edge counts and the dangling, new, orphan and overlap lists for one root."""
    names = walk(root)
    texts = {n: (root / n).read_text(encoding="utf-8", errors="replace") for n in names}
    edges, dangling = {}, []
    for name in names:
        for tok in refs(texts[name]):
            hit = resolve(root, name, tok)
            edges.setdefault(name, set()).add(hit) if hit else dangling.append((name, tok))
    inbound = dict.fromkeys(names, 0)
    for name, targets in edges.items():
        for target in targets & set(names) - {name}:
            inbound[target] += 1
    dangling, allowed = sorted(set(dangling)), allowlist(root)
    return {"names": names, "purpose": {n: purpose(texts[n]) for n in names}, "in": inbound,
            "out": {n: len(edges.get(n, ())) for n in names}, "dangling": dangling,
            "new": [p for p in dangling if p not in allowed], "overlaps": overlaps(texts),
            "orphans": [n for n in names if not inbound[n] and n not in ROOTS
                        and not n.endswith("SKILL.md") and "/agents/" not in "/" + n]}


def render(data: dict) -> str:
    """The DOCMAP text: the node table, then the Dangling, Orphans and Overlaps sections, all sorted."""
    out = [HEADER, "", "| path | purpose | in | out |", "|---|---|---|---|"]
    out += [f"| {n} | {data['purpose'][n].replace('|', '/')} | {data['in'][n]} | {data['out'][n]} |"
            for n in data["names"]]
    sections = (("Dangling", [f"- {n} :: {t}" for n, t in data["new"]]),
                ("Orphans", [f"- {n}" for n in data["orphans"]]),
                ("Overlaps", [f"- {', '.join(v)}: {k}" for k, v in data["overlaps"]]))
    for title, lines in sections:
        out += ["", f"## {title}", ""] + (lines or ["(none)"])
    return "\n".join(out) + "\n"


def check(root: pathlib.Path) -> int:
    """0 when the map is fresh and no dangling reference is new; orphans and overlaps print as WARN."""
    data = graph(root)
    stale = not (root / SELF).exists() or (root / SELF).read_text(encoding="utf-8") != render(data)
    print("FAIL stale: docs/DOCMAP.md is stale; run python tools/doc_graph.py") if stale else None
    for node, tok in data["new"]:
        print(f"FAIL dangling: {node} :: {tok}")
    for node in data["orphans"]:
        print(f"WARN orphan: {node}")
    for line, names in data["overlaps"]:
        print(f"WARN overlap: {', '.join(names)}: {line}")
    return 1 if stale or data["new"] else 0


def baseline(root: pathlib.Path, pairs: list) -> int:
    """Writes today's dangling pairs into the allowlist, sorted, keeping the ones already there."""
    path = root / ALLOW
    merged = sorted(allowlist(root) | set(pairs))
    head = ["# Dangling references accepted at the baseline, one node :: token per line.",
            "# A new pair fails tools/doc_graph.py --check; drop a line once its reference is fixed.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(head + [f"{n} :: {t}" for n, t in merged]) + "\n", encoding="utf-8", newline="\n")
    print(f"doc_graph: allowlisted {len(merged)} dangling reference(s) in {ALLOW}")
    return 0


def who_mentions(root: pathlib.Path, term: str) -> int:
    """Every node and code line holding the term, as path:line: text; exit 1 when there is none."""
    files = walk(root)
    for sub in CODE_DIRS:
        for dirpath, dirs, names in os.walk(root / sub):
            rel = pathlib.Path(dirpath).relative_to(root).as_posix()
            dirs[:] = sorted(d for d in dirs if not SKIP.match(rel + "/" + d))
            files += [rel + "/" + n for n in names if pathlib.Path(n).suffix in CODE_EXTS]
    hits = 0
    for name in sorted(set(files)):
        path = root / name
        if path.is_file():
            for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                if term in line:
                    print(f"{name}:{number}: {line.strip()}")
                    hits += 1
    return 0 if hits else 1


def main() -> int:
    """--root DIR, --check, --baseline, --who-mentions TERM; a plain run writes docs/DOCMAP.md and exits 0."""
    parser = argparse.ArgumentParser(description="Doc graph: nodes, edges, dangling refs, orphans, overlaps.")
    parser.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parent.parent))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--baseline", action="store_true")
    parser.add_argument("--who-mentions", metavar="TERM")
    args = parser.parse_args()
    root = pathlib.Path(args.root).resolve()
    if args.who_mentions is not None:
        return who_mentions(root, args.who_mentions)
    if args.check:
        return check(root)
    data = graph(root)
    if args.baseline:
        return baseline(root, data["dangling"])
    (root / SELF).parent.mkdir(parents=True, exist_ok=True)
    (root / SELF).write_text(render(data), encoding="utf-8", newline="\n")
    print(f"doc_graph: wrote docs/DOCMAP.md ({len(data['names'])} nodes, {len(data['new'])} dangling)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
