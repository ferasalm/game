"""Self-tests for tools/doc_graph.py: the generated DOCMAP must stay byte-stable, skip archive folders and itself, show purposes, resolve references, and flag dangling pairs, orphans, overlaps and a stale map."""
import os
import subprocess
import sys
import tempfile

TOOLS = os.path.dirname(os.path.abspath(__file__)).replace("\\", "/")


def put(path, text):
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def toy(files):
    root = tempfile.mkdtemp().replace("\\", "/")
    for name, text in files.items():
        put(root + "/" + name, text)
    return root


def run(root, *args):
    return subprocess.run(
        [sys.executable, TOOLS + "/doc_graph.py", "--root", root, *args],
        capture_output=True, text=True, stdin=subprocess.DEVNULL)


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def out(result):
    return result.stdout + result.stderr


def test_default_run_writes_a_stable_docmap():
    root = toy({"docs/a.md": "# a purpose line\nsee docs/b.md\n",
                "docs/b.md": "---\ndescription: b front matter purpose\n---\n"})
    assert run(root).returncode == 0
    first = read(root + "/docs/DOCMAP.md")
    assert run(root).returncode == 0
    second = read(root + "/docs/DOCMAP.md")
    assert first == second, (first, second)
    assert "generated by tools/doc_graph.py" in first, first
    assert "docs/a.md" in first and "a purpose line" in first, first
    assert "docs/b.md" in first and "b front matter purpose" in first, first


def test_nodes_skip_archive_research_inbox_and_the_map_itself():
    skipped = ["docs/archive/old.md", "docs/research/old.md", "inbox/old.md", ".check/old.md"]
    files = dict([("docs/keep.md", "# keep purpose\n")] +
                 [(name, "# skipped purpose\n") for name in skipped] +
                 [("docs/DOCMAP.md", "# map own purpose\n")])
    root = toy(files)
    assert run(root).returncode == 0
    text = read(root + "/docs/DOCMAP.md")
    assert "docs/keep.md" in text, text
    for gone in skipped + ["docs/DOCMAP.md", "map own purpose"]:
        assert gone not in text, (gone, text)


def test_purpose_is_the_front_matter_description_else_the_first_text_line():
    root = toy({
        "docs/front.md": "---\ndescription: front-matter purpose\n---\n# front heading\n",
        "docs/plain.md": "\n\n# heading purpose text\nbody\n",
    })
    assert run(root).returncode == 0
    text = read(root + "/docs/DOCMAP.md")
    assert "front-matter purpose" in text and "heading purpose text" in text, text
    assert "# heading purpose text" not in text and "front heading" not in text, text


def test_a_reference_resolves_from_the_root_or_the_documents_own_folder():
    root = toy({
        "docs/guide.md": "# guide purpose\nsee docs/fromroot.md and sub/beside.md not docs/gone.md\n",
        "docs/fromroot.md": "# fromroot purpose\n",
        "docs/sub/beside.md": "# beside purpose\n",
    })
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 1 and "docs/gone.md" in out(r), out(r)
    assert "sub/beside.md" not in out(r) and "docs/fromroot.md" not in out(r), out(r)


def test_tokens_with_wildcards_placeholders_urls_and_dotdot_are_ignored():
    body = ("docs/*.md docs/<name>.md docs/{x}.md docs/$x.md "
            "https://example.com/x.md tools/../docs/missing.md\n")
    root = toy({"docs/t.md": "# t purpose\n" + body})
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 0, out(r)


def test_a_path_under_dot_check_is_scratch_not_a_reference():  # an audit report cites .check/audit/ and failed the next check.sh
    root = toy({"docs/t.md": "# t purpose\n.check/audit/memory/MEMORY.md and .check/\n"})
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 0, out(r)


def test_an_at_import_is_an_edge():
    root = toy({
        "docs/main.md": "# main purpose\nrun @step.md then @gone.md\n",
        "docs/step.md": "# step purpose\n",
    })
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 1 and "gone.md" in out(r), out(r)
    assert "docs/step.md" not in out(r), out(r)


def test_check_fails_on_a_dangling_reference_and_names_it():
    root = toy({
        "docs/index.md": "# index purpose\nstart at docs/a.md\n",
        "docs/a.md": "# a purpose\nsee docs/gone.md for details\n",
    })
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 1, out(r)
    assert "docs/a.md" in out(r) and "docs/gone.md" in out(r), out(r)


def test_the_allowlist_silences_exactly_that_pair():
    root = toy({
        "docs/index.md": "# index purpose\nread docs/a.md and docs/b.md\n",
        "docs/a.md": "# a purpose\nsee docs/gone.md\n",
        "docs/b.md": "# b purpose\nsee docs/gone.md again\n",
        "docs/doc_graph_allow.txt": "docs/a.md :: docs/gone.md\n",
    })
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 1 and "docs/gone.md" in out(r), out(r)
    assert "docs/a.md" not in out(r), out(r)


def test_baseline_writes_the_current_dangling_pairs_sorted_and_check_then_passes():
    root = toy({"docs/a.md": "# a purpose\nsee docs/zz-gone.md before docs/aa-gone.md\n"})
    assert run(root).returncode == 0
    assert run(root, "--baseline").returncode == 0
    text = read(root + "/docs/doc_graph_allow.txt")
    assert "docs/a.md :: docs/aa-gone.md" in text and "docs/a.md :: docs/zz-gone.md" in text, text
    assert text.index("docs/aa-gone.md") < text.index("docs/zz-gone.md"), text
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 0, out(r)


def test_orphans_warn_but_do_not_fail_and_roots_are_not_orphans():
    names = ["CLAUDE.md", "HANDOFF.md", "README.md", "docs/MAP.md",
             "skills/kit/SKILL.md", "agents/a.md", "docs/x.md"]
    root = toy({name: "# shared purpose\n" for name in names})
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 0, out(r)
    assert any("WARN" in line and "docs/x.md" in line for line in out(r).splitlines()), out(r)
    for name in names[:-1]:
        assert name not in out(r), (name, out(r))


def test_overlap_needs_two_different_files_and_80_characters():
    shared = "sharedline docs/p1.md docs/p2.md " + "a" * 57
    short = "shortline " + "b" * 50
    fenced = "fencedline " + "c" * 79
    solo = "sololine " + "d" * 81
    page = "# p purpose\n%s\n%s\n```\n%s\n```\n" % (shared, short, fenced)
    root = toy({"docs/p1.md": page, "docs/p2.md": page,
                "docs/solo.md": "# solo purpose\n%s\n%s\n" % (solo, solo)})
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 0 and "sharedline" in out(r), out(r)
    assert "shortline" not in out(r) and "fencedline" not in out(r) and "sololine" not in out(r), out(r)


def test_check_fails_when_docmap_is_stale():
    root = toy({"docs/a.md": "# a purpose\n"})
    assert run(root).returncode == 0
    put(root + "/docs/a.md", "# a new purpose\n")
    assert run(root, "--check").returncode == 1
    assert run(root).returncode == 0
    assert run(root, "--check").returncode == 0


def test_who_mentions_finds_docs_and_code_lines_and_exits_1_when_none():
    root = toy({"docs/note.md": "# note purpose\nthe zebra runs\n",
                "tools/x.py": "zebra = 1\n"})
    r = run(root, "--who-mentions", "zebra")
    assert r.returncode == 0, out(r)
    assert "docs/note.md:2:" in out(r) and "tools/x.py:1:" in out(r), out(r)
    assert run(root, "--who-mentions", "nothing").returncode == 1


def test_check_sh_runs_the_graph_after_doc_check():
    text = read(TOOLS + "/../tools/check.sh")
    assert "doc_check.py" in text and "doc_graph.py --check" in text, text
    assert text.index("doc_check.py") < text.index("doc_graph.py --check"), text


def test_in_a_git_checkout_an_ignored_file_and_a_wrong_case_do_not_resolve():  # CI failed on main for exactly this (row 27)
    root = toy({".gitignore": "cfg/local.json\n", "cfg/local.json": "{}\n", "docs/b.md": "# b purpose\n",
                "docs/a.md": "# a purpose\nsee cfg/local.json and Docs/b.md and docs/b.md\n"})
    subprocess.run(["git", "init", "-q", root], check=True, capture_output=True)
    assert run(root).returncode == 0
    r = run(root, "--check")
    assert r.returncode == 1, out(r)
    assert "local.json" in out(r) and "Docs/b.md" in out(r), out(r)
    assert "FAIL dangling: docs/a.md :: docs/b.md" not in out(r), out(r)


def test_the_real_repo_has_a_fresh_map_and_no_new_dangling_reference():
    r = run(TOOLS + "/..", "--check")
    assert r.returncode == 0, out(r)


